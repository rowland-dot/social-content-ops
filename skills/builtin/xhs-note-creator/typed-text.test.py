# 9. issue 104: a block whose drawn box (outline and shadow included) crosses the 5% safe margin is refused
# (5% of the width left and right, 5% of the height top and bottom): non-zero exit, no output image, a message naming
# the block, its box and the margin. A block fully inside is set and recorded as before.
proc, out, record = set_words("margin-top", styling(), [{"text": "TITLE", "level": "main title", "at": [0.5, 0.02]}])
check(proc.returncode != 0, "a block centred at 2% of the height (cut off at the top) was set")
check(not out.exists() and not record.exists(), "a refused block still wrote an output image or a record")
check("TITLE" in proc.stderr and "margin" in proc.stderr.lower(),
      f"the refusal does not name the block and the margin: {proc.stderr.strip()[-300:]}")
proc, out, _ = set_words("margin-side", styling(), [{"text": "TITLE", "level": "main title", "at": [0.02, 0.5]}])
check(proc.returncode != 0 and not out.exists(), "a block centred at 2% of the width was set")
inside = [{"text": "TITLE", "level": "subtitle", "at": [0.5, 0.82]}]
proc, out, record = set_words("margin-inside", styling(), inside)
check(proc.returncode == 0 and out.is_file(), f"a block fully inside the margin was refused: {proc.stderr.strip()[-300:]}")
