"""Red/green check for issue 81: the word setter in scripts/text_on_image.py (typed fonts set by code).

Run: python skills/builtin/xhs-note-creator/typed-text.test.py   (exit 0 = pass). It drives the script through
its command line on plain images made here, so no image is generated by a model. tests/test_xhs_reference_visual_skill.py
runs this file too, which is how CI collects it.

Seams (the issue's "Agreed seams", 1, 2 and 4):
  1. the setter: image + stored styling + a card's text blocks -> the words set with the styling's font, fill, outline
     and shadow at one size per title level, image size unchanged, the card's record of the values used written out;
  2. the comparison check: every card's record against the set's stored styling, failing on any difference other than
     the per-level size.
"""

import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
SCRIPT = HERE / "scripts" / "text_on_image.py"

NOTO_SERIF = Path("/usr/share/fonts/opentype/noto/NotoSerifCJK-Bold.ttc")
FONT_CANDIDATES = [
    NOTO_SERIF,
    Path("/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc"),
    Path("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
    Path("C:/Windows/Fonts/arialbd.ttf"),
    Path("C:/Windows/Fonts/arial.ttf"),
]

BACKGROUND = (200, 200, 200)
FILL = (255, 255, 255)
OUTLINE = (176, 128, 80)  # a milk-tea brown, like the approved cover's outline
SHADOW = (0, 0, 255)

failures = []
font = next((p for p in FONT_CANDIDATES if p.is_file()), None)
if font is None:
    print("FAIL no usable font on this machine for the test images")
    sys.exit(1)

work = Path(tempfile.mkdtemp(prefix="typed-text-"))


def plain_image(name, size=(400, 300)):
    path = work / name
    Image.new("RGB", size, BACKGROUND).save(path)
    return path


def write_json(name, data):
    path = work / name
    path.write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
    return path


def styling(**changes):
    base = {
        "font_file": font.as_posix(),
        "fill": "#FFFFFF",
        "outline_width": 5,
        "outline_color": "#B08050",
        "shadow": None,
        "sizes": {"main title": 80, "subtitle": 40},
    }
    base.update(changes)
    return base


def run(*args, env=None):
    return subprocess.run([sys.executable, str(SCRIPT), *map(str, args)], capture_output=True, text=True, timeout=120,
                          env=env)


def set_words(card, style, blocks, size=(400, 300), env=None):
    """Set the blocks on a fresh plain image; return (process, output path, record path)."""
    source = plain_image(f"{card}-in.png", size)
    out, record = work / f"{card}-out.png", work / f"{card}-record.json"
    proc = run(source, out, "--styling", write_json(f"{card}-style.json", style),
               "--blocks", write_json(f"{card}-blocks.json", blocks), "--record", record, env=env)
    return proc, out, record


def read_record(path):
    """The card's record, or an empty one when the setter wrote none (the check then reports it)."""
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}


def pixels_of(path, colour):
    img = Image.open(path).convert("RGB")
    w, h = img.size
    data = img.load()
    return [(x, y) for y in range(h) for x in range(w) if data[x, y] == colour]


def bbox(points):
    xs, ys = [p[0] for p in points], [p[1] for p in points]
    return min(xs), min(ys), max(xs), max(ys)


def check(ok, message):
    if not ok:
        failures.append(message)


# 1. one block: fill inside, outline colour around it, image size unchanged (not cropped to 3:4)
proc, out, _ = set_words("one", styling(), [{"text": "TITLE", "level": "main title", "at": [0.5, 0.5]}])
check(proc.returncode == 0, f"the setter did not run on a styling and a block: {proc.stderr.strip()[-300:]}")
if proc.returncode == 0:
    check(Image.open(out).size == (400, 300), f"the setter changed the image size to {Image.open(out).size}")
    fill, outline = pixels_of(out, FILL), pixels_of(out, OUTLINE)
    check(bool(fill), "no pixel carries the styling's fill colour")
    check(bool(outline), "no pixel carries the styling's outline colour")
    if fill and outline:
        fx0, fy0, fx1, fy1 = bbox(fill)
        ox0, oy0, ox1, oy1 = bbox(outline)
        check(ox0 < fx0 and oy0 < fy0 and ox1 > fx1 and oy1 > fy1,
              "the outline colour does not appear around the letters (all four sides)")

# 2. two levels on two images from one styling: the size follows the level, the record says what was used
procs = {}
for card, level in (("cover", "main title"), ("card2", "subtitle")):
    procs[card] = set_words(card, styling(), [{"text": "TITLE", "level": level, "at": [0.5, 0.5]}])
for card, (proc, out, record) in procs.items():
    check(proc.returncode == 0, f"{card}: the setter did not run: {proc.stderr.strip()[-300:]}")
if all(p.returncode == 0 for p, _, _ in procs.values()):
    heights = {}
    for card, (_, out, _) in procs.items():
        x0, y0, x1, y1 = bbox(pixels_of(out, FILL))
        heights[card] = y1 - y0
    check(heights["cover"] > heights["card2"], f"the main title is not larger than the subtitle: {heights}")
    for card, level, size in (("cover", "main title", 80), ("card2", "subtitle", 40)):
        record = read_record(procs[card][2])
        for key, want in (("font_file", font.as_posix()), ("fill", "#FFFFFF"), ("outline_width", 5),
                          ("outline_color", "#B08050"), ("shadow", None)):
            check(record.get(key) == want, f"{card}: the record's {key} is {record.get(key)!r}, not {want!r}")
        used = [(b.get("level"), b.get("size")) for b in record.get("blocks", [])]
        check(used == [(level, size)], f"{card}: the record's blocks are {used}, not {[(level, size)]}")

# 3. the comparison check: the two cards match; one card with another outline width fails it
styling_file = write_json("set-style.json", styling())
good = run("--check-records", styling_file, procs["cover"][2], procs["card2"][2])
check(good.returncode == 0, f"the comparison failed two cards set from one styling: {good.stdout.strip()[-300:]}")
drift_proc, _, drift_record = set_words("card3", styling(outline_width=3),
                                        [{"text": "TITLE", "level": "subtitle", "at": [0.5, 0.5]}])
bad = run("--check-records", styling_file, procs["cover"][2], drift_record)
check(bad.returncode == 1, f"the comparison passed a card with another outline width (exit {bad.returncode})")
check("outline_width" in bad.stdout, f"the comparison did not name outline_width: {bad.stdout.strip()[-300:]}")
for what, changes in (("fill", {"fill": "#FFEEDD"}), ("font_file", {"font_file": "Other-Serif.ttc"}),
                      ("outline_color", {"outline_color": "#000000"}),
                      ("shadow", {"shadow": {"dx": 4, "dy": 4, "color": "#0000FF"}})):
    record = read_record(procs["cover"][2])
    record.update(changes)
    changed = write_json(f"drift-{what}.json", record)
    proc = run("--check-records", styling_file, changed)
    check(proc.returncode == 1 and what in proc.stdout, f"the comparison did not fail on a different {what}")
record = read_record(procs["cover"][2]) or {"blocks": [{}]}
record["blocks"][0]["size"] = 79
resized = run("--check-records", styling_file, write_json("drift-size.json", record))
check(resized.returncode == 1, "the comparison passed a card whose title size is not the set's size for that level")
record["blocks"][0]["size"], record["blocks"][0]["level"] = 80, "caption"
unknown = run("--check-records", styling_file, write_json("drift-level.json", record))
check(unknown.returncode == 1, "the comparison passed a block whose title level is not in the set's styling")

# 4. a shadow in the styling shows up in the picture, down and right of the letters
proc, out, _ = set_words("shadow", styling(shadow={"dx": 8, "dy": 8, "color": "#0000FF"}),
                         [{"text": "TITLE", "level": "main title", "at": [0.5, 0.5]}])
check(proc.returncode == 0, f"the setter did not run with a shadow: {proc.stderr.strip()[-300:]}")
if proc.returncode == 0:
    check(bool(pixels_of(out, SHADOW)), "no pixel carries the styling's shadow colour")

# 5. a font that is not there stops the run; it never falls back to a default font
proc, _, _ = set_words("nofont", styling(font_file="NoSuchFont-Bold.ttc"),
                       [{"text": "TITLE", "level": "main title", "at": [0.5, 0.5]}])
check(proc.returncode != 0, "the setter carried on with a font that is not installed")

# 6. the installed Noto fonts are found on this WSL without --font (only where they are installed)
script_text = SCRIPT.read_text(encoding="utf-8")
check("/usr/share/fonts/opentype/noto/" in script_text, "the font search does not look in /usr/share/fonts/opentype/noto/")
if NOTO_SERIF.is_file():
    proc, out, _ = set_words("noto", styling(font_file="NotoSerifCJK-Bold.ttc"),
                             [{"text": "燕麦蛋白", "level": "main title", "at": [0.5, 0.5]}])
    check(proc.returncode == 0, f"a styling naming NotoSerifCJK-Bold.ttc was not found: {proc.stderr.strip()[-300:]}")
    legacy = run(plain_image("legacy-in.png"), work / "legacy-out.png", "--text", "燕麦蛋白")
    check("no CJK font found" not in legacy.stderr, "without --font the script still falls back to the default font here")
else:
    print("note: Noto Serif CJK SC is not installed on this machine; the WSL font checks were not run")

# 7. issue 116: LXGW WenKai Medium, the third typed font, is found by its bare file name with no path
# (the setup step puts it in /usr/local/share/fonts/lxgw-wenkai/; the check that runs everywhere is the folder in the
# search list, the live one runs where the font is installed)
LXGW_DIR = "/usr/local/share/fonts/lxgw-wenkai"
LXGW_FILE = Path(LXGW_DIR) / "LXGWWenKai-Medium.ttf"
check(LXGW_DIR + "/" in script_text or f'Path("{LXGW_DIR}")' in script_text,
      f"the font search does not look in {LXGW_DIR}")
if LXGW_FILE.is_file():
    words = [{"text": "燕麦蛋白", "level": "main title", "at": [0.5, 0.5]}]
    proc, lxgw_out, _ = set_words("lxgw", styling(font_file="LXGWWenKai-Medium.ttf"), words)
    check(proc.returncode == 0, f"a styling naming LXGWWenKai-Medium.ttf by bare name was not found: {proc.stderr.strip()[-300:]}")
    if proc.returncode == 0 and NOTO_SERIF.is_file():
        _, serif_out, _ = set_words("serif-same-words", styling(font_file="NotoSerifCJK-Bold.ttc"), words)
        check(Image.open(lxgw_out).tobytes() != Image.open(serif_out).tobytes(),
              "the same words in LXGW WenKai and in Noto Serif CJK came out as the same picture")
else:
    print(f"note: {LXGW_FILE} is not installed on this machine; the live LXGW WenKai check was not run")

# 8. issue 119: a font installed on demand (one folder per font under the on-demand root) is found by its bare file name.
# The root is a setting (EASEL_ONDEMAND_FONT_ROOT, default /usr/local/share/fonts/on-demand) so this runs on a temporary one.
ondemand = work / "on-demand-root"
(ondemand / "ondemandtest-regular").mkdir(parents=True)
(ondemand / "ondemandtest-regular" / "OnDemandTest-Regular.ttf").write_bytes(font.read_bytes())
empty_root = work / "empty-on-demand-root"
empty_root.mkdir()
words = [{"text": "TITLE", "level": "main title", "at": [0.5, 0.5]}]
env_with = {**os.environ, "EASEL_ONDEMAND_FONT_ROOT": str(ondemand)}
proc, ondemand_out, _ = set_words("ondemand", styling(font_file="OnDemandTest-Regular.ttf"), words, env=env_with)
check(proc.returncode == 0, f"a styling naming a font in an on-demand subfolder by bare name was not found: {proc.stderr.strip()[-300:]}")
