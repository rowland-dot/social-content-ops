# 10. issue 126: the pick styles titles only. A styling may hold a "body" style beside the title style (font, fill, one size
# per body level; no outline, no shadow). Body blocks are set with it and never with the title's outline or shadow;
# --check-records fails a record whose body block uses a title level or a size not in the body style. A styling with
# no body style still works for title-only sets.
BODY_FILL = (20, 60, 120)
body_style = styling(outline_width=6, shadow={"dx": 3, "dy": 3, "color": "#0000FF"},
                     body={"font_file": font.as_posix(), "fill": "#143C78", "sizes": {"point": 36, "sub-line": 28}})
mixed = [{"text": "TITLE", "level": "main title", "at": [0.5, 0.2]},
         {"text": "POINT", "level": "point", "at": [0.5, 0.6]},
         {"text": "SUB", "level": "sub-line", "at": [0.5, 0.8]}]
proc, out, record = set_words("body-ok", body_style, mixed)
check(proc.returncode == 0 and out.is_file(), f"a body style with body blocks was refused: {proc.stderr.strip()[-300:]}")
if out.is_file():
    img_pixels = Image.open(out).convert("RGB")
    body_area = img_pixels.crop((0, int(300 * 0.45), 400, 300))  # below the title block
    seen = {c for _, c in body_area.getcolors(100000)}
    check(BODY_FILL in seen, "body text was not set in the body style's fill")
    check(OUTLINE not in seen and SHADOW not in seen, "body text carries the title's outline or shadow")
rec = {"blocks": [], "body": {}, **read_record(record)}
check([(b.get("level"), b.get("size")) for b in rec.get("blocks", [])] == [("main title", 80), ("point", 36), ("sub-line", 28)],
      f"the record does not hold each block's level and size: {rec.get('blocks')}")
style_path = write_json("body-style.json", body_style)
good_record = write_json("body-good.json", rec)
proc = run("--check-records", style_path, good_record)
check(proc.returncode == 0, f"a matching body record failed the check: {proc.stdout.strip()[-300:]}")
# a body block set with a title level's styling fails
bad = json.loads(json.dumps(rec))
for b in bad["blocks"]:
    if b["level"] == "point":
        b["level"] = "main title"
        b["size"] = 80
        b["kind"] = "body"
proc = run("--check-records", style_path, write_json("body-bad-level.json", bad))
check(proc.returncode != 0 and "body" in proc.stdout, "a body block with a title level did not fail the check")
# a body size that is not the body style's size fails
bad = json.loads(json.dumps(rec))
for b in bad["blocks"]:
    if b["level"] == "point":
        b["size"] = 40
proc = run("--check-records", style_path, write_json("body-bad-size.json", bad))
check(proc.returncode != 0 and "point" in proc.stdout, "a body size other than the body style's did not fail the check")
# a record whose body carries an outline fails
bad = json.loads(json.dumps(rec))
bad["body"]["outline_width"] = 4
proc = run("--check-records", style_path, write_json("body-bad-outline.json", bad))
check(proc.returncode != 0, "a record whose body carries an outline did not fail the check")
# a body level used with a styling that has no body style stops the run; a title-only styling is unchanged
proc, out, _ = set_words("body-none", styling(), [{"text": "POINT", "level": "point", "at": [0.5, 0.6]}])
check(proc.returncode != 0 and not out.exists(), "a body block was set although the styling has no body style")
proc, out, record = set_words("title-only", styling(), [{"text": "TITLE", "level": "main title", "at": [0.5, 0.3]}])
check(proc.returncode == 0 and "body" not in read_record(record), "a title-only styling gained a body entry in the record")
proc = run("--check-records", write_json("title-only-style.json", styling()), record)
check(proc.returncode == 0, "a title-only record failed against a title-only styling")

# 11. issue 127: a styling may carry one "title_size". A block marked "role": "title" (the cover's title or a card's page
# title) is set at that size whatever its level, the record keeps it, and --check-records fails a title block of any other
# size. A styling without "title_size" behaves as before.
ts_style = styling(title_size=70)
ts_blocks = [{"text": "TITLE", "level": "main title", "role": "title", "at": [0.5, 0.2]},
             {"text": "PAGE", "level": "subtitle", "role": "title", "at": [0.5, 0.5]}]
proc, out, record = set_words("title-size", ts_style, ts_blocks)
check(proc.returncode == 0, f"a styling with title_size was refused: {proc.stderr.strip()[-300:]}")
ts_rec = read_record(record)
check([b.get("size") for b in ts_rec.get("blocks", [])] == [70, 70], f"title blocks are not all at title_size: {ts_rec.get('blocks')}")
ts_path = write_json("title-size-style.json", ts_style)
proc = run("--check-records", ts_path, write_json("title-size-good.json", ts_rec))
check(proc.returncode == 0, f"a record with every title at title_size failed: {proc.stdout.strip()[-300:]}")
bad = json.loads(json.dumps(ts_rec))
bad["blocks"][1]["size"] = 40
proc = run("--check-records", ts_path, write_json("title-size-bad.json", bad))
check(proc.returncode != 0 and "title_size" in proc.stdout, "a title smaller than title_size did not fail the check")

for line in failures:
    print("FAIL", line)
print("PASS" if not failures else f"{len(failures)} failed")
sys.exit(1 if failures else 0)
